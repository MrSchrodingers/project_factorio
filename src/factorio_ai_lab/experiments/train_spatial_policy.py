from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from typing import Any

import numpy as np

from factorio_ai_lab.learning.model_arena import ModelArena, ModelCandidate
from factorio_ai_lab.learning.spatial_policy import (
    SpatialPolicy,
    examples_from_path,
    load_real_paths,
    random_route_tasks,
    route_cost,
)
from factorio_ai_lab.learning.torch_spatial_policy import TorchSpatialPolicy
from factorio_ai_lab.paths import CODE_ROOT as PROJECT_ROOT
from factorio_ai_lab.paths import RUNS_DIR

REAL_DEMOS = RUNS_DIR / "datasets" / "spatial_demonstrations.jsonl"
MODEL_DIR = RUNS_DIR / "models"
MLP_MODEL_PATH = MODEL_DIR / "spatial_policy_mlp.npz"
ATTENTION_MODEL_PATH = MODEL_DIR / "spatial_policy_attention.pt"
METADATA_PATH = MODEL_DIR / "spatial_policy.json"
MODEL_REGISTRY = MODEL_DIR / "model_registry.json"


def _evaluate_rollouts(
    model: Any,
    *,
    validation_tasks: list,
    turn_penalty: float,
) -> dict[str, float | int]:
    in_bounds = lambda point: 0 <= point.x < 20 and 0 <= point.y < 20
    successes = 0
    ratios: list[float] = []
    for start, goal, blocked, _, astar_cost in validation_tasks:
        path = model.rollout(
            start,
            goal,
            is_blocked=blocked.__contains__,
            in_bounds=in_bounds,
            max_steps=800,
        )
        if path is None:
            continue
        successes += 1
        candidate_cost = route_cost(path, turn_penalty=turn_penalty)
        ratios.append(candidate_cost / max(astar_cost, 1e-9))

    return {
        "rollout_tasks": len(validation_tasks),
        "rollout_successes": successes,
        "rollout_success_rate": successes / max(1, len(validation_tasks)),
        "mean_cost_ratio_to_astar": (
            float(np.mean(ratios)) if ratios else float("inf")
        ),
    }


def train(
    *,
    synthetic_train: int = 1200,
    synthetic_validation: int = 240,
    seed: int = 20260921,
    turn_penalty: float = 0.35,
) -> dict[str, object]:
    training_tasks = random_route_tasks(
        count=synthetic_train,
        width=20,
        height=20,
        obstacle_probability=0.12,
        seed=seed,
        turn_penalty=turn_penalty,
    )
    validation_tasks = random_route_tasks(
        count=synthetic_validation,
        width=20,
        height=20,
        obstacle_probability=0.12,
        seed=seed + 1,
        turn_penalty=turn_penalty,
    )

    train_x: list[np.ndarray] = []
    train_y: list[int] = []
    in_bounds = lambda point: 0 <= point.x < 20 and 0 <= point.y < 20
    for _, _, blocked, path, _ in training_tasks:
        x_rows, y_rows = examples_from_path(
            path,
            blocked=blocked,
            in_bounds=in_bounds,
        )
        train_x.extend(x_rows)
        train_y.extend(y_rows)

    real_paths = load_real_paths(REAL_DEMOS)
    for path in real_paths:
        min_x = min(point.x for point in path) - 4
        max_x = max(point.x for point in path) + 4
        min_y = min(point.y for point in path) - 4
        max_y = max(point.y for point in path) + 4
        real_bounds = lambda point, a=min_x, b=max_x, c=min_y, d=max_y: (
            a <= point.x <= b and c <= point.y <= d
        )
        x_rows, y_rows = examples_from_path(
            path,
            blocked=set(),
            in_bounds=real_bounds,
        )
        # Real accepted demonstrations receive extra weight but do not dominate
        # the synthetic coverage generated by the deterministic teacher.
        for _ in range(8):
            train_x.extend(x_rows)
            train_y.extend(y_rows)

    val_x: list[np.ndarray] = []
    val_y: list[int] = []
    for _, _, blocked, path, _ in validation_tasks:
        x_rows, y_rows = examples_from_path(
            path,
            blocked=blocked,
            in_bounds=in_bounds,
        )
        val_x.extend(x_rows)
        val_y.extend(y_rows)

    x_train = np.vstack(train_x)
    y_train = np.asarray(train_y, dtype=np.int64)
    x_validation = np.vstack(val_x)
    y_validation = np.asarray(val_y, dtype=np.int64)

    mlp = SpatialPolicy(hidden_size=64, seed=seed)
    mlp.fit(
        x_train,
        y_train,
        epochs=70,
        learning_rate=0.012,
    )
    mlp_accuracy = mlp.accuracy(x_validation, y_validation)
    mlp_rollout = _evaluate_rollouts(
        mlp,
        validation_tasks=validation_tasks,
        turn_penalty=turn_penalty,
    )
    mlp_usable = (
        float(mlp_rollout["rollout_success_rate"]) >= 0.80
        and float(mlp_rollout["mean_cost_ratio_to_astar"]) <= 1.15
        and mlp_accuracy >= 0.80
    )
    mlp.save(MLP_MODEL_PATH)

    attention = TorchSpatialPolicy(
        d_model=48,
        heads=4,
        layers=2,
        seed=seed,
    )
    attention_fit = attention.fit(
        x_train,
        y_train,
        validation=(x_validation, y_validation),
        epochs=40,
        batch_size=256,
        patience=7,
    )
    attention_rollout = _evaluate_rollouts(
        attention,
        validation_tasks=validation_tasks,
        turn_penalty=turn_penalty,
    )
    attention_cost = float(attention_rollout["mean_cost_ratio_to_astar"])
    mlp_cost = float(mlp_rollout["mean_cost_ratio_to_astar"])
    attention_usable = (
        float(attention_rollout["rollout_success_rate"]) >= 0.90
        and attention_cost <= 1.12
        and attention_fit.validation_accuracy >= 0.85
        and attention_cost <= mlp_cost
    )
    attention_control_eligible = (
        attention_usable
        and float(attention_rollout["rollout_success_rate"]) >= 0.97
        and attention_cost <= 1.08
    )
    attention.save(ATTENTION_MODEL_PATH)

    active_model: str | None = None
    if attention_usable:
        active_model = "attention"
    elif mlp_usable:
        active_model = "mlp"

    active_candidate: ModelCandidate | None = None
    if active_model == "attention":
        active_candidate = ModelCandidate(
            task="spatial_policy",
            model_id="torch_attention",
            protocol="spatial-v1-grid20-obstacle012-seed-fixed",
            eligible=attention_usable,
            primary_score=attention_cost,
            secondary_score=1.0 - float(
                attention_rollout["rollout_success_rate"]
            ),
            artifact=str(ATTENTION_MODEL_PATH.relative_to(PROJECT_ROOT)),
            metadata={
                "validation_accuracy": attention_fit.validation_accuracy,
                "control_eligible": attention_control_eligible,
            },
        )
    elif active_model == "mlp":
        active_candidate = ModelCandidate(
            task="spatial_policy",
            model_id="numpy_mlp",
            protocol="spatial-v1-grid20-obstacle012-seed-fixed",
            eligible=mlp_usable,
            primary_score=mlp_cost,
            secondary_score=1.0 - float(
                mlp_rollout["rollout_success_rate"]
            ),
            artifact=str(MLP_MODEL_PATH.relative_to(PROJECT_ROOT)),
            metadata={"validation_accuracy": mlp_accuracy},
        )

    model_selection = (
        ModelArena(MODEL_REGISTRY).select(active_candidate).to_dict()
        if active_candidate is not None
        else None
    )

    metadata: dict[str, object] = {
        "trained_at": datetime.now(UTC).isoformat(),
        "teacher": "weighted_astar",
        "synthetic_training_routes": len(training_tasks),
        "synthetic_validation_routes": len(validation_tasks),
        "real_factorio_demonstrations": len(real_paths),
        "training_examples": len(train_x),
        "validation_examples": len(val_x),
        "active_model": active_model,
        "usable": active_model is not None,
        "control_eligible": attention_control_eligible,
        "model_selection": model_selection,
        "baselines": {
            "mlp": {
                "model_type": "numpy_mlp_autoregressive_route_policy",
                "model_path": str(MLP_MODEL_PATH.relative_to(PROJECT_ROOT)),
                "validation_accuracy": mlp_accuracy,
                **mlp_rollout,
                "usable": mlp_usable,
            }
        },
        "candidates": {
            "attention": {
                "model_type": "torch_transformer_local_route_policy",
                "model_path": str(
                    ATTENTION_MODEL_PATH.relative_to(PROJECT_ROOT)
                ),
                **attention_fit.to_dict(),
                **attention_rollout,
                "usable": attention_usable,
                "control_eligible": attention_control_eligible,
            }
        },
        # Compatibility fields consumed by the current dashboard.
        "validation_accuracy": (
            attention_fit.validation_accuracy
            if active_model == "attention"
            else mlp_accuracy
        ),
        "rollout_success_rate": (
            float(attention_rollout["rollout_success_rate"])
            if active_model == "attention"
            else float(mlp_rollout["rollout_success_rate"])
        ),
        "mean_cost_ratio_to_astar": (
            attention_cost
            if active_model == "attention"
            else mlp_cost
        ),
    }
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    METADATA_PATH.write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--synthetic-train", type=int, default=1200)
    parser.add_argument("--synthetic-validation", type=int, default=240)
    parser.add_argument("--seed", type=int, default=20260921)
    args = parser.parse_args()
    print(
        json.dumps(
            train(
                synthetic_train=args.synthetic_train,
                synthetic_validation=args.synthetic_validation,
                seed=args.seed,
            ),
            indent=2,
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
